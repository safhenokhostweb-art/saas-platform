const fs = require('fs');
const path = require('path');
const { ROOT, enhance, loadContext } = require('./engine');

const context = loadContext();
const exampleFiles = fs.readdirSync(path.join(ROOT, 'examples')).filter((file) => file.endsWith('.json')).sort();
const results = exampleFiles.map((file) => {
  const input = JSON.parse(fs.readFileSync(path.join(ROOT, 'examples', file), 'utf8'));
  return { file, output: enhance(input, context) };
});
const totalRecommendations = results.reduce((sum, item) => sum + item.output.recommendations.flatMap((section) => section.recommendations).length, 0);
const allThemeReady = results.every((item) => item.output.recommendations.flatMap((section) => section.recommendations).every((asset) => asset.theme_ready));

const lines = [
  '# Smart Template Enhancement Prototype Report',
  '',
  'This report is generated by a read-only prototype. It does not modify or publish assets.',
  '',
  '## Library context',
  '',
  `- Canonical assets loaded: ${context.library.assets.length}`,
  `- Canonical relation bundles loaded: ${context.relations.relationships.length}`,
  `- Standard tags loaded: ${context.tags.tags.length}`,
  `- Example scenarios: ${results.length}`,
  `- Recommendations generated: ${totalRecommendations}`,
  `- All recommended assets theme-ready: ${allThemeReady ? 'yes' : 'no'}`,
  '',
  '## Scenario scores',
  '',
  '| Scenario | Industry | Before | After | Improvement |',
  '|---|---|---:|---:|---:|',
  ...results.map(({ file, output }) => `| ${file} | ${output.business.industry} | ${output.enhancement_score.before} | ${output.enhancement_score.after} | +${output.enhancement_score.improvement} |`),
  '',
  '## Architecture decisions',
  '',
  '- Deterministic rules run before any future AI suggestion.',
  '- Recommendations reference immutable Master Asset IDs and paths; assets are never copied.',
  '- Eligibility is limited to active, platform-owned Master Assets with quality score 70 or higher.',
  '- Industry has the highest matching weight, followed by section usage and asset type.',
  '- Brand adaptation is an approval-required handoff using the five canonical theme tokens.',
  '- AI is a local placeholder that cannot call providers, create variants, approve, or publish.',
  '',
  '## Future integration boundary',
  '',
  'A future Template Builder may submit the documented input contract and render returned recommendations for Platform Admin review. Integration must preserve server-side authorization, published-version resolution, licensing, tenant isolation, and immutable asset lineage.'
];

const outputPath = path.join(ROOT, 'reports', 'engine-analysis.md');
fs.writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');
process.stdout.write(`Analyzed ${context.library.assets.length} assets across ${results.length} scenarios.\n`);
