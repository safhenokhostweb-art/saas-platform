<?php

namespace SaaSPlatform\Modules\Education\Services;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use SaaSPlatform\Modules\Education\Models\EducationArticle;
use SaaSPlatform\Modules\Education\Models\EducationMedia;

class EducationMediaService
{
    public function attachToArticle(EducationArticle $article, array $data, ?UploadedFile $file = null): EducationMedia
    {
        if ($file) {
            $path = $file->store('education/media', 'public');
            $data['video_provider'] = 'local';
            $data['video_path']     = $path;
            $data['type']           = $data['type'] ?? ($this->isVideo($file) ? 'video' : 'image');
        }

        $data['edu_article_id'] = $article->id;
        $data['sort_order']     = $data['sort_order'] ?? ($article->media()->max('sort_order') + 1);

        return EducationMedia::create($data);
    }

    public function attachExternal(EducationArticle $article, string $provider, string $videoId, array $extra = []): EducationMedia
    {
        return EducationMedia::create(array_merge([
            'edu_article_id'  => $article->id,
            'type'            => 'video',
            'video_provider'  => $provider,
            'video_path'      => $videoId,
            'sort_order'      => $article->media()->max('sort_order') + 1,
        ], $extra));
    }

    public function markAutoGenerated(EducationMedia $media): void
    {
        $media->update(['auto_generated' => true]);
    }

    public function delete(EducationMedia $media): void
    {
        if ($media->video_provider === 'local' && $media->video_path) {
            Storage::disk('public')->delete($media->video_path);
        }
        $media->delete();
    }

    public function reorder(EducationArticle $article, array $orderedIds): void
    {
        foreach ($orderedIds as $position => $mediaId) {
            EducationMedia::where('id', $mediaId)
                ->where('edu_article_id', $article->id)
                ->update(['sort_order' => $position]);
        }
    }

    private function isVideo(UploadedFile $file): bool
    {
        return str_starts_with($file->getMimeType(), 'video/');
    }
}
