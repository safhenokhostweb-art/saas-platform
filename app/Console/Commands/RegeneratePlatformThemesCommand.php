<?php
namespace App\Console\Commands;

use App\Services\ThemeBuilder\ThemeCleanupService;
use Database\Seeders\ProfessionalThemesSeeder;
use Illuminate\Console\Command;

class RegeneratePlatformThemesCommand extends Command
{
    protected $signature = 'themes:regenerate
                            {--no-cleanup : Skip deleting existing auto-generated themes}
                            {--force : Run even if no auto-generated themes exist}';

    protected $description = 'Remove auto-generated themes and create exactly 3 production-ready platform themes (Corporate, Personal Brand, E-Commerce)';

    public function handle(ThemeCleanupService $cleanup): int
    {
        if (!$this->option('no-cleanup')) {
            $this->info('Cleaning up auto-generated themes...');
            $result = $cleanup->deleteAutoGeneratedThemes();
            $this->info(sprintf(
                'Removed %d theme(s), detached %d site(s).',
                $result['deleted_count'],
                $result['detached_sites_count']
            ));
            if ($result['deleted_count'] > 0 && $this->output->isVerbose()) {
                $this->line('Deleted slugs: ' . implode(', ', $result['deleted_slugs']));
            }
        } else {
            $this->warn('Skipping cleanup (--no-cleanup).');
        }

        $this->info('Seeding 3 professional themes...');
        $this->call('db:seed', ['--class' => ProfessionalThemesSeeder::class, '--force' => true]);

        $this->info('Done. Exactly 3 professional themes are now available.');
        return self::SUCCESS;
    }
}
